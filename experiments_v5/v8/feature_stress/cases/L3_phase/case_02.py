"""
L3-phase stress case 02: Dropout applied during eval without phase guard.

Target feature: train/eval phase check (L3).
Bug: The model applies Dropout(0.5) unconditionally (no self.training check).
In eval mode this is silently wrong: outputs are randomly zeroed, causing
non-deterministic predictions. A phase-aware analyser should flag this.

Honest: phase violations not generated by current verify_model. L3 = no-op.
"""
import torch
import torch.nn as nn


class AlwaysDropout(nn.Module):
    """Applies Dropout regardless of training/eval mode."""

    def __init__(self, p: float = 0.5):
        super().__init__()
        self.fc = nn.Linear(32, 32)
        # BUG: dropout not guarded by self.training
        self.dropout = nn.Dropout(p=p)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        h = self.fc(x)
        # Should be: if self.training: h = self.dropout(h)
        return self.dropout(h)   # wrong in eval mode


