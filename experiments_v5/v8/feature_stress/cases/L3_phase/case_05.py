import torch
import torch.nn as nn


class NoRunningStatsBN(nn.Module):
    def __init__(self, features: int = 32):
        super().__init__()
        self.fc = nn.Linear(features, features)
        # BUG: track_running_stats=False → eval mode uses batch mean/var
        self.bn = nn.BatchNorm1d(features, track_running_stats=False)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        h = self.fc(x)
        return self.bn(h)  # In eval mode, batch stats with batch size 1 → NaN


