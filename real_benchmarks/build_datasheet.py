#!/usr/bin/env python3
"""Generate ``real_benchmarks/DATASHEET.md`` from the frozen manifest.

The datasheet follows *Datasheets for Datasets* (Gebru et al., 2021). It is
generated — never hand-edited — from ``real_benchmarks/manifest.json`` so the
quantitative parts (counts by label / domain / provenance, the per-item table,
the content hashes) can never drift from the corpus they describe. This makes
the corpus a standalone, citable contribution: a reviewer can verify every
number in the datasheet against the manifest, and ``load.py`` re-verifies every
SHA-256 before use.

Usage::

    python -m real_benchmarks.build_datasheet            # write DATASHEET.md
    python -m real_benchmarks.build_datasheet --check    # verify it is current
"""

from __future__ import annotations

import argparse
import collections
import json
import os

THIS_DIR = os.path.dirname(os.path.abspath(__file__))
MANIFEST = os.path.join(THIS_DIR, "manifest.json")
OUT = os.path.join(THIS_DIR, "DATASHEET.md")


def _load():
    with open(MANIFEST, encoding="utf-8") as fh:
        return json.load(fh)


def render(manifest: dict) -> str:
    meta = manifest["meta"]
    items = sorted(manifest["items"], key=lambda it: it["id"])
    by_label = collections.Counter(it["label"] for it in items)
    by_domain = collections.Counter(it["domain"] for it in items)
    by_prov = collections.Counter(it["provenance_type"] for it in items)
    n_issue = sum(1 for it in items if it["provenance_type"] == "pytorch_issue")

    def count_table(counter, head):
        rows = [f"| {head} | Count |", "| --- | --- |"]
        for k, v in sorted(counter.items()):
            rows.append(f"| `{k}` | {v} |")
        return "\n".join(rows)

    lines = [
        f"# Datasheet — {meta['name']} v{meta['version']}",
        "",
        "_Generated by `real_benchmarks/build_datasheet.py` from "
        "`manifest.json`. Do not edit by hand._ Follows *Datasheets for "
        "Datasets* (Gebru et al., 2021).",
        "",
        f"- **Frozen:** {meta.get('frozen')}  ",
        f"- **Schema version:** {meta.get('schema_version')}  ",
        f"- **Size:** {meta['total']} models "
        f"({by_label.get('clean', 0)} clean / {by_label.get('buggy', 0)} buggy)",
        "",
        "## Motivation",
        "",
        "- **For what purpose was the dataset created?** To measure the "
        "accuracy of static bug detectors for PyTorch `nn.Module`s against a "
        "stable, executable ground truth that cannot silently drift. Each model "
        "is labeled `clean` (should verify **SAFE**) or `buggy` (should verify "
        "**UNSAFE**).",
        "- **Who created it and how is it maintained?** The TensorGuard "
        "maintainers; it is versioned (`VERSION`), content-addressed by SHA-256 "
        "in `manifest.json`, and regenerated by `build_manifest.py`.",
        "",
        "## Composition",
        "",
        f"The corpus contains **{meta['total']} standalone PyTorch modules**. "
        "Every file is a self-contained `.py` with a provenance header and an "
        "`INPUT_SHAPES` contract.",
        "",
        "### By label",
        "",
        count_table(by_label, "Label"),
        "",
        "### By bug domain",
        "",
        count_table(by_domain, "Domain"),
        "",
        "### By provenance",
        "",
        count_table(by_prov, "Provenance"),
        "",
        f"Of the buggy models, **{n_issue}** are drawn from tracked "
        "`pytorch/pytorch` issues (the issue URL is recorded in `source_url`); "
        "the remaining canonical patterns capture the two real-world failure "
        "modes (device mismatch, silent gradient detach) that runtime testing "
        "handles poorly.",
        "",
        "### Per-item index",
        "",
        "| id | label | domain | provenance | expected verdict | source | sha256 (first 12) |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for it in items:
        src = it.get("source_url") or "—"
        if src != "—":
            src = f"[issue]({src})"
        lines.append(
            f"| `{it['id']}` | {it['label']} | {it['domain']} | "
            f"{it['provenance_type']} | {it['expected_verdict']} | {src} | "
            f"`{it['sha256'][:12]}` |"
        )

    lines += [
        "",
        "## Collection & labeling process",
        "",
        "- **How were instances acquired?** Buggy models were distilled from "
        "real `pytorch/pytorch` issue reports and two canonical failure patterns;"
        " clean models are minimal, idiomatic architectures.",
        "- **How are labels grounded (not the tool's opinion)?** Most buggy "
        "models raise a real `RuntimeError` when executed in eager PyTorch (the "
        "`expected_error_substring` field records the message); the device bug "
        "raises only on a CUDA host; the gradient-detach bug is *silent* (raises "
        "no exception), which is exactly why static verification matters. Clean "
        "models are validated to execute without error before admission.",
        "",
        "## Uses",
        "",
        "- **Intended use:** benchmarking precision/recall/F1 of static and "
        "runtime bug detectors (see `evaluation/precision_recall.py`, "
        "`evaluation/significance.py`).",
        "- **Out-of-scope:** the corpus is intentionally small and curated; it "
        "is a *ground-truth correctness* benchmark, not a representative sample "
        "of all PyTorch code. Headline accuracy numbers are always reported with "
        "honest sample-size caveats (n = %d)." % meta["total"],
        "",
        "## Distribution & licensing",
        "",
        "- Distributed with the TensorGuard repository under the repository's "
        "MIT license (see `LICENSE`). Each file is content-addressed; the "
        "manifest is the citable, frozen description.",
        "- **Citation:** see `CITATION.cff` in the repository root.",
        "",
        "## Maintenance",
        "",
        "- **Versioning:** the `VERSION` file and `meta.version` are bumped on "
        "any change; the SHA-256 manifest guarantees byte-level immutability "
        "within a version.",
        "- **Extending:** add a model to `corpus_def.py` and run "
        "`python -m real_benchmarks.build_manifest`; `build_datasheet.py` then "
        "regenerates this document.",
        "",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="verify DATASHEET.md is up to date")
    args = ap.parse_args()
    text = render(_load())
    if args.check:
        if not os.path.exists(OUT):
            raise SystemExit("DATASHEET.md missing; run without --check first")
        with open(OUT, encoding="utf-8") as fh:
            current = fh.read()
        if current != text:
            raise SystemExit("DATASHEET.md is stale; regenerate it")
        print("DATASHEET.md is up to date")
        return
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
