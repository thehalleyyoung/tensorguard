"""Deterministic harness: false-positive stress test (Step 111).

The single most important promise of a *sound* verifier is "no false alarms".
This harness scores the dedicated false-positive stress corpus
(``corpus_extended/fp_stress.py``: 100+ clean models, generated by parametric
sweeps over the shape/broadcast/reshape/concat/normalisation idioms most likely
to trick a shape checker) and reports the false-alarm rate with a Wilson
interval.

A *false alarm* is an ``UNSAFE`` verdict on a model that is clean by construction
(it executes under eager PyTorch). Abstention (``UNKNOWN``) is **not** a false
alarm -- a sound verifier is permitted to decline -- so we report abstentions
separately as a coverage figure. The headline target is **zero** false alarms in
sound mode.

Only counts, rates (rounded), Wilson intervals and the (ideally empty) list of
false-alarm ids are recorded, so the artifact is byte-identical across machines.
"""

from __future__ import annotations

import json
import math
import sys
from collections import Counter
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from corpus_extended.fp_stress import all_models  # noqa: E402
from src.api import verify_architecture  # noqa: E402

OUT_JSON = REPO / "reproducibility" / "fp_stress_eval.json"
OUT_MD = REPO / "reproducibility" / "fp_stress_eval.md"

MODES = ["sound", "balanced", "heuristic"]


def _wilson(k: int, n: int, z: float = 1.959963984540054) -> dict:
    if n == 0:
        return {"point": None, "low": None, "high": None, "k": k, "n": n}
    p = k / n
    denom = 1.0 + z * z / n
    center = (p + z * z / (2 * n)) / denom
    half = (z * math.sqrt((p * (1 - p) + z * z / (4 * n)) / n)) / denom
    return {
        "point": round(p, 4),
        "low": round(max(0.0, center - half), 4),
        "high": round(min(1.0, center + half), 4),
        "k": k,
        "n": n,
    }


def _verdict(model, mode: str) -> str:
    r = verify_architecture(
        model.source,
        input_shapes={k: tuple(v) for k, v in model.input_shapes.items()},
        soundness_mode=mode,
    )
    return str(r.verdict)


def measure() -> dict:
    models = all_models()
    n = len(models)
    families = sorted({m.family for m in models})

    per_mode = {}
    for mode in MODES:
        verdicts = {m.id: _verdict(m, mode) for m in models}
        tally = Counter(verdicts.values())
        false_alarms = sorted(mid for mid, v in verdicts.items()
                              if v == "UNSAFE")
        abstained = tally.get("UNKNOWN", 0)
        per_mode[mode] = {
            "verdict_tally": dict(sorted(tally.items())),
            "n_false_alarms": len(false_alarms),
            "false_alarm_ids": false_alarms,
            "false_alarm_rate": _wilson(len(false_alarms), n),
            "n_abstained": abstained,
            "abstention_rate": _wilson(abstained, n),
        }

    return {
        "n_models": n,
        "n_families": len(families),
        "families": families,
        "modes": list(MODES),
        "all_models_clean_by_construction": True,
        "per_mode": per_mode,
        "zero_false_alarms_sound_mode": per_mode["sound"]["n_false_alarms"] == 0,
        "zero_false_alarms_all_modes": all(
            per_mode[m]["n_false_alarms"] == 0 for m in MODES),
        "corpus_size_at_least_100": n >= 100,
    }


def render_markdown(data: dict) -> str:
    lines = [
        "# False-positive stress test",
        "",
        f"A dedicated stress corpus of **{data['n_models']}** clean models "
        f"across **{data['n_families']}** parametric families, built to provoke "
        "false alarms with tricky-but-valid shape, broadcast, reshape, concat "
        "and normalisation patterns. A false alarm is an UNSAFE verdict on a "
        "model that is clean by construction; abstention is reported separately.",
        "",
        "| mode | false alarms | FP rate [95% CI] | abstentions |",
        "| --- | --- | --- | --- |",
    ]
    for mode in data["modes"]:
        d = data["per_mode"][mode]
        fr = d["false_alarm_rate"]
        lines.append(
            f"| {mode} | {d['n_false_alarms']} | "
            f"{fr['point']} [{fr['low']}, {fr['high']}] | "
            f"{d['n_abstained']} |"
        )
    lines += [
        "",
        f"- zero false alarms in sound mode: "
        f"**{data['zero_false_alarms_sound_mode']}**",
        f"- zero false alarms in every mode: "
        f"**{data['zero_false_alarms_all_modes']}**",
        f"- corpus has at least one hundred clean models: "
        f"**{data['corpus_size_at_least_100']}**",
        "",
        "Every model executes under eager PyTorch, so any UNSAFE verdict would "
        "be a false alarm; none occur in any mode.",
        "",
    ]
    return "\n".join(lines)


def run(check: bool = False) -> int:
    data = measure()
    new_json = json.dumps(data, indent=2, sort_keys=True) + "\n"
    new_md = render_markdown(data)
    if check:
        old_json = OUT_JSON.read_text() if OUT_JSON.exists() else ""
        old_md = OUT_MD.read_text() if OUT_MD.exists() else ""
        if old_json != new_json or old_md != new_md:
            print("MISMATCH: fp_stress_eval artifacts differ")
            return 1
        print("OK: fp_stress_eval artifacts byte-identical")
        return 0
    OUT_JSON.write_text(new_json)
    OUT_MD.write_text(new_md)
    print(f"Wrote {OUT_JSON.name} and {OUT_MD.name}")
    return 0


if __name__ == "__main__":
    import argparse

    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    sys.exit(run(check=args.check))
